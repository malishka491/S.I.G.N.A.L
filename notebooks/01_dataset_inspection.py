import pandas as pd

file_path = "data/raw/news/Media Reported Road Traffic Crash Data/Data Files/News Crashes.xlsx"

df = pd.read_excel(file_path)

print("Dataset loaded successfully!")
print("Number of rows:", len(df))
print("Number of columns:", len(df.columns))

print("\nColumn names:")
print(df.columns.tolist())
print("\nFirst 5 records:")
print(df.head())
print("\nMissing values:")
print(df.isnull().sum())
print("\nData types:")
print(df.dtypes)
print("\nRoad Type values:")
print(df["Road Type"].value_counts())
print("\n Records by state:")
print(df["State"].value_counts())
print("\nRoad type by state:")
print(pd.crosstab(df["State"], df["Road Type"]))
print("\nSample locations:")
print(df[["Location", "State", "Road Type", "LatLong"]].head(20).to_string(index=False))
print("\nMissing LatLong values:")
print(df["LatLong"].isnull().sum())
print("\nCoordinate format examples:")
print(df["LatLong"].head(10).tolist())
print("\nCrash date range:")
crash_dates = pd.to_datetime(df["Crash Date"], errors="coerce")
print("Earliest:", crash_dates.min())
print("Latest:", crash_dates.max())
print("\nRecords by year:")
print(crash_dates.dt.year.value_counts().sort_index())
print("\nCrash types:")
print(df["Crash Type"].value_counts())

nh_df = df[df["Road Type"] == "NH"]
print("\nNH records:", len(nh_df))
print("\nNH crash types:")
print(nh_df["Crash Type"].value_counts())
print("\nUnique NH locations:")
print(nh_df["Location"].nunique())
print("\nDuplicate rows:")
print(df.duplicated().sum())
print("\nMissing values in NH records:")
print(nh_df.isnull().sum())

print("\nNH Killed statistics:")
print(nh_df["Killed"].describe())
print("\nNH Injured statistics:")
print(nh_df["Injured"].describe())
print("\nVehicle 1 types:")
print(nh_df["Vehicle 1"].value_counts().head(20))
print("\nVehicle/Object 2 types:")
print(nh_df["Vehicle/Object 2"].value_counts().head(20))
print("\nGender values:")
print(nh_df["Gender"].value_counts(dropna=False))
print("\nAge values:")
print(nh_df["Age"].value_counts(dropna=False).head(20))

print("\nRoad Type vs Crash Type:")
print(pd.crosstab(df["Road Type"], df["Crash Type"]))

print("\nNH crashes by month:")
print(nh_df["Month "].value_counts())
print("\nNH crashes by day:")
print(nh_df["Crash Day"].value_counts())
print("\nNH crashes by year:")
print(crash_dates[nh_df.index].dt.year.value_counts().sort_index())

print("\nArticle date range:")
print("Earliest:", df["Article Date "].min())
print("Latest:", df["Article Date "].max())
print("\nInvalid Crash Dates:")
print(crash_dates.isna().sum())

print("\nMissing NH locations:")
print(nh_df["Location"].isna().sum())
print("\nBlank NH locations:")
print((nh_df["Location"].str.strip() == "").sum())
print("\nLocations with multiple coordinates:")
location_coords = nh_df.groupby("Location")["LatLong"].nunique()
print(location_coords[location_coords > 1].head(20))
print("\nDuplicate NH coordinates:")
print(nh_df["LatLong"].duplicated().sum())
print("\nDuplicate NH coordinates:")
print(nh_df["LatLong"].duplicated().sum())

coords = nh_df["LatLong"].str.split(",", expand=True)
latitude = pd.to_numeric(coords[0].str.strip(), errors="coerce")
longitude = pd.to_numeric(coords[1].str.strip(), errors="coerce")
print("\nInvalid latitude:", ((latitude < 6) | (latitude > 38)).sum())
print("Invalid longitude:", ((longitude < 68) | (longitude > 98)).sum())

print("\nHigh-severity NH crashes (5+ deaths):")
print((nh_df["Killed"] >= 5).sum())
print("\nMaximum deaths in an NH crash:")
print(nh_df["Killed"].max())
print("\nTop 10 most severe NH crashes:")
print(
    nh_df.nlargest(10, "Killed")
    [["Crash Date", "Location", "State", "Killed", "Injured", "Crash Type"]]
)
max_deaths = nh_df["Killed"].max()
print("\nMaximum deaths:", max_deaths)
print("\nCrash(es) with maximum deaths:")
print(
    nh_df[nh_df["Killed"] == max_deaths]
    [["Crash Date", "Location", "State", "Killed", "Injured", "Crash Type"]]
)
print("\nNH crashes with zero deaths:")
print((nh_df["Killed"] == 0).sum())
print("\nNH crashes with zero injuries:")
print((nh_df["Injured"] == 0).sum())
print("\nNegative deaths:", (nh_df["Killed"] < 0).sum())
print("Negative injuries:", (nh_df["Injured"] < 0).sum())
print("\nUnique Road Type values:")
print(nh_df["Road Type"].unique())
print("/n Unique NH Crash Type values:")
print(nh_df["Crash Type"].unique())
print("\nUnique states:")
print(nh_df["State"].unique())

print("\nNH records by state:")
print(nh_df["State"].value_counts().sort_values(ascending=False))
print("\nMillion Plus City values:")
print(nh_df["Million Plus City"].value_counts())
print("\nMillion-plus city records by state:")
print(
    nh_df[nh_df["Million Plus City"].notna()]
    .groupby("State")["Million Plus City"]
    .count()
    .sort_values(ascending=False)
)

print("\nTop NH crash locations:")
print(nh_df["Location"].value_counts().head(20))

print("\n===== COLUMNS =====")
print(df.columns.tolist())

print("\n===== SAMPLE DATA =====")
print(df.head(5).to_string())

print("\n===== DATA TYPES =====")
print(df.dtypes)